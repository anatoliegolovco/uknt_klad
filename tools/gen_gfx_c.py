#!/usr/bin/env python3
"""
Extract tile + sprite pixel data from KLAD_1987_Baranov.SAV and output
src/gfx_data.h with exact 8×8 arrays (values 0-3 = palette index).

Palette:
  0 = black  (pixel=0, color=0)
  1 = green  (pixel=1, color=0)  — water
  2 = yellow (pixel=0, color=1)  — gold
  3 = white  (pixel=1, color=1)  — walls, ladders, player

Usage:
  python3 tools/gen_gfx_c.py > src/gfx_data.h
"""

import sys
from pathlib import Path

SAV = Path(__file__).parent.parent / "assets/original/extracted/uknc/KLAD_1987_Baranov.SAV"

def load_prog():
    raw = SAV.read_bytes()
    return raw[512:]   # strip 512-byte RT-11 header; prog at 001000

def decode_tile(data16):
    """Return 8×8 array of palette indices (0-3)."""
    result = []
    for row in range(8):
        p_byte = data16[row]
        c_byte = data16[row + 8]
        row_pixels = []
        for col in range(8):
            bit = 7 - col   # MSB = leftmost pixel
            p = (p_byte >> bit) & 1
            c = (c_byte >> bit) & 1
            row_pixels.append(p | (c << 1))
        result.append(row_pixels)
    return result

def tile_c_array(pixels, name, index):
    lines = [f"  /* {index}: {name} */", "  {"]
    for row in pixels:
        lines.append("    {" + ",".join(str(v) for v in row) + "},")
    lines.append("  },")
    return "\n".join(lines)

def main():
    prog = load_prog()
    out = []
    out.append("// Auto-generated by tools/gen_gfx_c.py — do not edit.")
    out.append("// Source: KLAD_1987_Baranov.SAV tile bank (017450) + sprite bank (031300)")
    out.append("// Each value: 0=black, 1=green, 2=yellow, 3=white (УКНЦ 2bpp palette)")
    out.append("#pragma once")
    out.append("#include <stdint.h>")
    out.append("")

    # ── Tiles (017450, stride 16, 32 entries) ────────────────────────────────
    # Indices 0-15 = level tiles. Indices 16-31 = character sprite tiles,
    # confirmed from ANIMATIONS.md + table 012410 (states 0o21-0o24 reference
    # tiles 16,18,20,21,22,25). The УКНЦ draws the character as 2 of these tiles
    # overlaid 1px apart (planar SPRITE_DRAW 014030).
    TILE_NAMES = {
        0: "bg_empty",    1: "ladder",       2: "exit",        3: "empty3",
        4: "gold_a",      5: "gold_b",       6: "gold_c",      7: "water",
        8: "ladder2",     9: "wall_a",      10: "empty10",    11: "wall_b",
       12: "wall_c",     13: "wall_d",      14: "water2",     15: "empty15",
       16: "char_a",     17: "char_b",      18: "char_climb", 19: "char_climb2",
       20: "char_walk0", 21: "char_walk1",  22: "char_walk2", 23: "char_walk3",
       24: "char_c",     25: "char_d",      26: "char26",     27: "char27",
       28: "char28",     29: "char29",      30: "char30",     31: "char31",
    }
    bank_off = 0o17450 - 0o1000
    out.append("// TILE_GFX[tile_index][row][col] — 32 entries (0-15 level, 16-31 character)")
    out.append("static const uint8_t TILE_GFX[32][8][8] = {")
    for t in range(32):
        off = bank_off + t * 16
        pixels = decode_tile(prog[off:off + 16])
        name = TILE_NAMES.get(t, f"tile{t}")
        out.append(tile_c_array(pixels, name, t))
    out.append("};")
    out.append("")

    # Note: the sprite bank at 031300 (208 frames) was previously extracted here,
    # but the player/enemy character is NOT drawn from it — it comes from the
    # tile bank entries 16-31 (see ANIMATIONS.md). Bank 031300 holds intro/title
    # frames only, so it is no longer emitted.

    # ── Palette RGB for convenience ──────────────────────────────────────────
    out.append("// UKNC_PAL[palette_index] = {R, G, B}")
    out.append("// 0=black, 1=green(water), 2=yellow(gold), 3=white(walls/ladder/player)")
    out.append("static const uint8_t UKNC_PAL[4][3] = {")
    out.append("  {  0,   0,   0},  /* 0 black  */")
    out.append("  {  0, 192,   0},  /* 1 green  */")
    out.append("  {210, 200,   0},  /* 2 yellow */")
    out.append("  {236, 236, 236},  /* 3 white  */")
    out.append("};")
    out.append("")

    print("\n".join(out))

if __name__ == "__main__":
    main()
